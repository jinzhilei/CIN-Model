%==========================================================================
% Function: main_Figure_S5
% Purpose: Main wrapper function for Figure S5 (Circular dendrogram).
% Call plotCircularDendrogram to compute damage index, Ward hierarchical 
% clustering, draw circular dendrogram, and calculate sample size of two clusters.
% Required dependent function: plotCircularDendrogram.m
%==========================================================================
function main_Figure_S5(outputDir)
    % Handle input arguments for output directory
    if nargin < 1
        outputDir = 'Figure';
    end

    % Call circular dendrogram function, read data_Eindex.csv, return cluster labels T
    T = plotCircularDendrogram('New_Eindex.csv');
    
    % Capture the figure handle generated by the plotting function
    fig = gcf;
    
    % Count the number of samples in each cluster
    n1 = sum(T == 1);
    n2 = sum(T == 2);
    
    % Output sample sizes to command window for manuscript results
    fprintf('Class1: %d, Class2: %d\n', n1, n2);

    % -------- Save Figure --------
    if ~isempty(outputDir)
        if ~exist(outputDir, 'dir')
            mkdir(outputDir);
        end
        outFile = fullfile(outputDir, 'Figure_S5.png');
        exportgraphics(fig, outFile, 'Resolution', 300);
        fprintf('Saved: %s\n', outFile);
    end
end


