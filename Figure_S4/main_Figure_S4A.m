function main_Figure_S4A(outputDir) 

    % Handle input arguments for output directory
    if nargin < 1
        outputDir = 'Figure';
    end

    %--------------------------------------------------------------------------
    % Simulation configuration
    %--------------------------------------------------------------------------
    t_start = 0;                             % Start time (hours)
    n_cycles = 19;                           % Number of treatment cycles
    dt_hours = 0.1;                          % Time step (hours)
    cycle_length = 21;                       % Cycle length (days)
    t_total_days = n_cycles * cycle_length;  % Total simulation time (days)
    t_end = t_total_days*24;                 % End time (hours)
    th = 1;

    %--------------------------------------------------------------------------
    % Load clinical averaged neutrophil data (Severe group)
    %--------------------------------------------------------------------------
    tic
    [neutrophil_average] = Data();

    %--------------------------------------------------------------------------
    % PK simulation: capecitabine and G-CSF concentration
    %--------------------------------------------------------------------------
    wp_cycles = 15;                           % Warm-up cycles
    wp_days = wp_cycles * cycle_length;
    dt_days = dt_hours/24;
    n_zero_points = ceil(wp_days/dt_days);   % Index for warm-up period

    C_cap = simulate_capecitabine_concentration(n_cycles,dt_hours,cycle_length);
    C_csf = simulate_gcsf_concentration(n_cycles,dt_hours,cycle_length);
    C_csf(1:n_zero_points) = 0;
    C_cap(1:n_zero_points) = 0;

    %--------------------------------------------------------------------------
    % ODE model setup
    %--------------------------------------------------------------------------
    model = @HSCs_Cap_Gcsf_Model_new;        % Custom ODE model function
    initial = [1.1,2.26,3.54,0.9];           % Initial condition of ODE state variables

    % Assign observed neutrophil data for Severe group
    Neu = neutrophil_average;

    % Load PSO optimized parameters for Severe group
    load ('PSO/params_Average.mat'); 
    param = params_opt';

    %--------------------------------------------------------------------------
    % Solve ODE system
    %--------------------------------------------------------------------------
    [T, Y] = Solve(t_start, dt_hours, t_end, th, param, C_cap, C_csf, model, initial);

    %--------------------------------------------------------------------------
    % Generate Figure S4A and Save
    %--------------------------------------------------------------------------
    fun_Figure_S4A(T, Y, Neu);
    fig = gcf; % Capture the figure generated by the plotting function
    toc

    % -------- Save Figure --------
    if ~isempty(outputDir)
        if ~exist(outputDir, 'dir')
            mkdir(outputDir);
        end
        outFile = fullfile(outputDir, 'Figure_S4A.png');
        exportgraphics(fig, outFile, 'Resolution', 300);
        fprintf('Saved: %s\n', outFile);
    end

end