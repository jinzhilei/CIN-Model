%==========================================================================
% Function: main_Figure_4B
% Purpose: Main wrapper function for Figure 4B.
% Calls plotDamageIndexClustering to compute damage index,
% perform Ward hierarchical clustering (fixed 2 clusters) and draw histogram,
% then calculate sample counts for the two subgroups.
%==========================================================================
function main_Figure_4B()
    % 1. Run clustering and plotting function
    cluster_idx = plotDamageIndexClustering('New_Eindex.csv');

    % 2. Capture the figure handle generated by the plotting function
    fig = gcf;

    % 3. Calculate sample size for each cluster
    n1 = sum(cluster_idx == 1);
    n2 = sum(cluster_idx == 2);
    
    % Print group sample numbers to command window
    fprintf('Group 1 sample size: %d\n', n1);
    fprintf('Group 2 sample size: %d\n', n2);

    % -------- Save Figure --------
    outputDir = 'Figure';
    if ~isempty(outputDir)
        if ~exist(outputDir, 'dir')
            mkdir(outputDir);
        end
        outFile = fullfile(outputDir, 'Figure_4B.png');
        exportgraphics(fig, outFile, 'Resolution', 300);
        fprintf('Saved: %s\n', outFile);
    end
end