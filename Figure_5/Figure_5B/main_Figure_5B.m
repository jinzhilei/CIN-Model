function main_Figure_5B(outputDir) 
%==========================================================================
% main_Figure_5B() 
% param(i:): i=1 is Severe group; i =2 is Moderate group
% Simulation for severe neutropenia group, solve ODE model and plot Figure 5B
%
% Dependencies:
%   Function files: Data.m, simulate_capecitabine_concentration.m,
%                   simulate_gcsf_concentration.m, HSCs_Cap_Gcsf_Model_new.m,
%                   Solve.m, fun_Figure_5B.m
%   Data file: PSO/params_Severe.mat；PSO/params_Moderate.mat
%
% Description:
% 1. Load group-averaged neutrophil data for two cohorts
% 2. Call plotting function fun_Figure_5B to generate Figure 5B
%==========================================================================

% Handle input arguments for output directory
if nargin < 1
    outputDir = 'Figure';
end

%--------------------------------------------------------------------------
% Simulation configuration
%--------------------------------------------------------------------------
t_start = 0;                             % Start time (hours)
n_cycles = 19;                           % Number of treatment cycles
dt_hours = 0.1;                          % Time step (hours)
cycle_length = 21;                       % Cycle length (days)
t_total_days = n_cycles * cycle_length;  % Total simulation time (days)
t_end = t_total_days*24;                 % End time (hours)
th = 1;

%--------------------------------------------------------------------------
% Load clinical averaged neutrophil data (Severe and Moderate)
%--------------------------------------------------------------------------
tic
[neutrophil_group1_average, neutrophil_group2_average] = Data();

%--------------------------------------------------------------------------
% PK simulation: capecitabine and G-CSF concentration
%--------------------------------------------------------------------------
wp_cycles = 15;                           % Warm-up cycles
wp_days = wp_cycles * cycle_length;
dt_days = dt_hours/24;
n_zero_points = ceil(wp_days/dt_days);   % Index for warm-up period

C_cap = simulate_capecitabine_concentration(n_cycles,dt_hours,cycle_length);
C_csf = simulate_gcsf_concentration(n_cycles,dt_hours,cycle_length);
C_csf(1:n_zero_points) = 0;
C_cap(1:n_zero_points) = 0;

%--------------------------------------------------------------------------
% ODE model setup
%--------------------------------------------------------------------------
model = @HSCs_Cap_Gcsf_Model_new;        % Custom ODE model function
initial = [1.1,2.26,3.54,0.9];           % Initial condition of ODE state variables

% Assign observed neutrophil data for Severe group
Neu = [neutrophil_group1_average; neutrophil_group2_average];

% Load PSO optimized parameters for Severe group
load ('PSO/params_Severe.mat'); 
param_Severe = params_opt';
load ('PSO/params_Moderate.mat'); 
param_Moderate = params_opt';
param = [param_Severe; param_Moderate];

%--------------------------------------------------------------------------
% Solve ODE system
%--------------------------------------------------------------------------
[T, Y_severe] = Solve(t_start, dt_hours, t_end, th, param(1,:), C_cap, C_csf, model, initial);

[T, Y_moderate] = Solve(t_start, dt_hours, t_end, th, param(2,:), C_cap, C_csf, model, initial);

Y = [Y_severe(3,:); Y_moderate(3,:)];

%--------------------------------------------------------------------------
% Generate Figure 5B and Save
%--------------------------------------------------------------------------
fun_Figure_5B(T, Y, Neu);
fig = gcf; % Capture the figure generated by the plotting function
toc

% -------- Save Figure --------
if ~isempty(outputDir)
    if ~exist(outputDir, 'dir')
        mkdir(outputDir);
    end
    outFile = fullfile(outputDir, 'Figure_5B.png');
    exportgraphics(fig, outFile, 'Resolution', 300);
    fprintf('Saved: %s\n', outFile);
end

end

